// หน่วยเป็น world px — กล้องจะ scale ตามจอเอง
//   ห้องเล็กลงจาก 1600×1000 → 1400×900 (บรีฟ: "ไม่ทำห้องใหญ่จนเดินนาน")
//   จอ 1440×900 เห็นทั้งห้องพอดีในเฟรมเดียว
// ============================================

export const MAP = {
  width: 1400,
  height: 900,

  // ผนังข้าง/ล่าง (หินดวงจันทร์ + ขอบทองหม่น) — collision ต้องตรงกับภาพที่เจนใน tools/gen_library.py
  wallThickness: 48,

  // ผนังเหนือ = หน้าต่างโค้งใหญ่มองเห็นพื้นผิวดวงจันทร์ + โลก — สูง 170 เดินขึ้นไปทับไม่ได้
  northWallH: 170,

  // หน้าต่างโค้ง (world px) — ★ ต้องตรงกับ WINDOW ใน tools/gen_library.py
  window: { x0: 330, x1: 1070, top: 16, bottom: 152, arc: 70 },

  // จุดเกิด = ลานโล่งกลางห้อง (ลายวงโคจรบนพื้น) — เหนือโต๊ะต้อนรับเล็กน้อย
  spawn: { x: 700, y: 520 },
};

// กำแพงรอบห้อง (AABB: x, y, w, h)
const T = MAP.wallThickness;
const NH = MAP.northWallH;
MAP.walls = [
  { x: 0, y: 0, w: MAP.width, h: NH },                   // บน — เต็มความสูงหน้าผนัง/หน้าต่าง
  { x: 0, y: MAP.height - T, w: MAP.width, h: T },       // ล่าง
  { x: 0, y: 0, w: T, h: MAP.height },                   // ซ้าย
  { x: MAP.width - T, y: 0, w: T, h: MAP.height },       // ขวา
];

// ขอบเขตพื้นที่เดินได้จริง (ใช้โดยเอฟเฟกต์/ระบบคลิกเดิน ให้ไม่หลุดเข้ากำแพง)
MAP.floor = {
  x0: T,
  y0: NH,
  x1: MAP.width - T,
  y1: MAP.height - T,
};
